// Explicit public source allowlist. Never snapshot an application checkout.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, unlinkSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const destination = path.join(root, 'integrations/sakura-rooms');
const files = [
  'sakura-mobile/app/perps/rooms.web.tsx',
  'sakura-mobile/app/perps/rooms.tsx',
  'sakura-mobile/components/rooms/rooms-screen.web.tsx',
  'sakura-mobile/components/rooms/rooms.web.css',
  'sakura-mobile/components/perps/perps-roadmap.web.css',
  'sakura-mobile/lib/rooms-client.web.ts',
  'sakura-mobile/lib/rooms-storage.web.ts',
  'web/test/rooms-app.browser.mjs',
];
const [mode, appPath] = process.argv.slice(2);
const write = (file, content) => { mkdirSync(path.dirname(file), { recursive: true }); writeFileSync(file, content); };
const copy = (from, to) => { mkdirSync(path.dirname(to), { recursive: true }); copyFileSync(from, to); };
const sha = value => createHash('sha256').update(value).digest('hex');
if (mode === 'capture') {
  if (!appPath || !path.isAbsolute(appPath) || !existsSync(path.join(appPath, 'sakura-mobile/app/_layout.tsx'))) throw new Error('Supply an absolute Sakura Expo source checkout.');
  for (const file of files) copy(path.join(appPath, file), path.join(destination, file));
  console.log(`Captured ${files.length} explicitly allowed public Rooms source files.`);
} else if (mode === 'engine') {
  // wasm-bindgen's no-modules output uses a global lexical binding, not a
  // Window property. Expose only this module's initializer under our namespace.
  const generated = readFileSync(path.join(root, 'target/rooms-web/sakura_rooms.js'));
  if (!generated.toString('utf8').startsWith('let wasm_bindgen =')) throw new Error('Unexpected wasm-bindgen global output');
  // Scope generated lexical bindings so a failed load can safely retry. Each
  // fresh client attempt must initialize its own manifest-pinned engine.
  const javascript = Buffer.concat([Buffer.from('(() => {\n'), generated, Buffer.from('\nglobalThis.sakura_rooms_engine = wasm_bindgen;\n})();\n')]);
  const wasm = readFileSync(path.join(root, 'target/rooms-web/sakura_rooms_bg.wasm'));
  const jsName = `rooms-${sha(javascript).slice(0, 20)}.js`;
  const wasmName = `rooms-${sha(wasm).slice(0, 20)}.wasm`;
  const publicRoot = path.join(destination, 'web/public/rooms-engine');
  write(path.join(publicRoot, jsName), javascript);
  write(path.join(publicRoot, wasmName), wasm);
  for (const name of readdirSync(publicRoot)) {
    if (/^rooms-[a-f0-9]{20}\.(js|wasm)$/.test(name) && ![jsName, wasmName].includes(name)) unlinkSync(path.join(publicRoot, name));
  }
  const version = { javascript: jsName, wasm: wasmName, integrity: `sha256-${createHash('sha256').update(javascript).digest('base64')}`, sha256: sha(wasm) };
  write(path.join(destination, 'sakura-mobile/lib/rooms-engine-version.ts'), `// Generated by scripts/build-rooms-web.sh. Content hashes prevent mixed engine versions.\nexport const ROOMS_ENGINE = ${JSON.stringify(version, null, 2)} as const;\n`);
  write(path.join(destination, 'engine-manifest.json'), JSON.stringify({ schema: 1, semanticVersion: 'sakura-rooms-paper/1', rust: '1.89.0', wasmBindgen: '0.2.126', ...version }, null, 2) + '\n');
  console.log(`Built Rooms engine (${wasm.length} bytes); hashes recorded.`);
} else if (mode === 'install' || mode === 'install-engine') {
  if (!appPath || !path.isAbsolute(appPath) || !existsSync(path.join(appPath, 'sakura-mobile/app/_layout.tsx'))) throw new Error('Supply an absolute Sakura Expo source checkout.');
  const version = JSON.parse(readFileSync(path.join(destination, 'engine-manifest.json'), 'utf8'));
  if (mode === 'install') {
    // Preflight the entire source set before writing anything. Application
    // updates must be consciously merged, never overwritten by this helper.
    for (const file of files) {
      if (existsSync(path.join(appPath, file)) && !readFileSync(path.join(appPath, file)).equals(readFileSync(path.join(destination, file)))) throw new Error(`Merge the existing application file before installing: ${file}`);
    }
    for (const file of files) copy(path.join(destination, file), path.join(appPath, file));
  }
  for (const name of [version.javascript, version.wasm]) copy(path.join(destination, 'web/public/rooms-engine', name), path.join(appPath, 'web/public/rooms-engine', name));
  copy(path.join(destination, 'sakura-mobile/lib/rooms-engine-version.ts'), path.join(appPath, 'sakura-mobile/lib/rooms-engine-version.ts'));
  console.log(mode === 'install' ? 'Installed the allowlisted Rooms integration and generated engine.' : 'Installed only the generated Rooms engine and version module.');
} else if (mode === 'check') {
  const version = JSON.parse(readFileSync(path.join(destination, 'engine-manifest.json'), 'utf8'));
  const wasm = readFileSync(path.join(destination, 'web/public/rooms-engine', version.wasm));
  const js = readFileSync(path.join(destination, 'web/public/rooms-engine', version.javascript));
  if (sha(wasm) !== version.sha256 || `sha256-${createHash('sha256').update(js).digest('base64')}` !== version.integrity) throw new Error('Engine artifact hash mismatch');
  if (version.javascript !== `rooms-${sha(js).slice(0, 20)}.js` || version.wasm !== `rooms-${sha(wasm).slice(0, 20)}.wasm`) throw new Error('Engine filename hash mismatch');
  for (const name of readdirSync(path.join(destination, 'web/public/rooms-engine'))) {
    if (![version.javascript, version.wasm].includes(name)) throw new Error(`Unexpected engine asset: ${name}`);
  }
  const expectedModule = `// Generated by scripts/build-rooms-web.sh. Content hashes prevent mixed engine versions.\nexport const ROOMS_ENGINE = ${JSON.stringify({ javascript: version.javascript, wasm: version.wasm, integrity: version.integrity, sha256: version.sha256 }, null, 2)} as const;\n`;
  if (readFileSync(path.join(destination, 'sakura-mobile/lib/rooms-engine-version.ts'), 'utf8') !== expectedModule) throw new Error('Engine version module differs from manifest');
  if (appPath) for (const file of [...files, 'sakura-mobile/lib/rooms-engine-version.ts']) {
    if (!readFileSync(path.join(appPath, file)).equals(readFileSync(path.join(destination, file)))) throw new Error(`Integration source differs: ${file}`);
  }
  const allowed = new Set([...files, 'sakura-mobile/lib/rooms-engine-version.ts']);
  const scan = (directory, prefix) => {
    for (const item of readdirSync(directory, { withFileTypes: true })) {
      const file = `${prefix}/${item.name}`;
      if (item.isSymbolicLink()) throw new Error('Integration sources must not be symlinks');
      if (item.isDirectory()) scan(path.join(directory, item.name), file);
      else if (!allowed.has(file)) throw new Error(`Unexpected application source: ${file}`);
    }
  };
  scan(path.join(destination, 'sakura-mobile'), 'sakura-mobile');
  scan(path.join(destination, 'web/test'), 'web/test');
  console.log('Rooms integration source allowlist and engine hashes verified.');
} else throw new Error('Usage: node scripts/package-rooms.mjs capture|install|install-engine <absolute Sakura path> | engine | check [absolute Sakura path]');
